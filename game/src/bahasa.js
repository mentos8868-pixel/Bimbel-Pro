const kode = ["id", "en", "zh-Hans"];
const nama = ["Bahasa Indonesia", "English", "中文（简体）"];
let bahasa = "id";
let profil;

export function terjemah(kunci) {
  return teks[kunci]?.[kode.indexOf(bahasa)] ?? kunci;
}

export function bahasaDashboard(id, render) {
  if (profil !== id) {
    profil = id;
    bahasa = "id";
    try {
      const simpan = localStorage.getItem("bahasa:" + profil);
      if (kode.includes(simpan)) bahasa = simpan;
    } catch {}
  }
  document.documentElement.lang = bahasa;
  for (const tombol of document.querySelectorAll("#menu [data-ke]")) {
    const label = tombol.firstChild;
    if (!tombol.dataset.labelAsli) tombol.dataset.labelAsli = label.textContent.trim();
    const [ikon, ...kata] = tombol.dataset.labelAsli.split(" ");
    label.textContent = ikon + " " + terjemah(kata.join(" ")) + " ";
  }
  const pilih = document.getElementById("bahasa-avatar");
  if (!pilih) return;
  pilih.value = bahasa;
  pilih.onchange = () => {
    bahasa = pilih.value;
    try { localStorage.setItem("bahasa:" + profil, bahasa); } catch {}
    render();
    document.getElementById("bahasa-avatar")?.focus();
  };
}

export function pilihanBahasa() {
  return '<section class="panel"><label>' + terjemah("Bahasa") + ' <select id="bahasa-avatar">' +
    kode.map((k, i) => '<option lang="' + k + '" value="' + k + '">' + nama[i] + '</option>').join("") +
    '</select></label></section>';
}

export function benderaBahasa() {
  return `<svg width="30" height="20" role="img" aria-label="${nama[kode.indexOf(bahasa)]}"><use href="/bendera-bahasa.svg#${bahasa}"/></svg>`;
}
