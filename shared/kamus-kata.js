const pisah = (teks) => teks.trim().split(/\s+/).filter((w) => /^[A-Z]{2,}$/.test(w));
const DAFTAR = { ID: pisah(ID), EN: pisah(EN) };

// Kata umum untuk satu bahasa: daftar di atas + semua kata soal Scramble. Dipakai bot Papan Kata
// (bot hanya memainkan kata yang dikenal anak) dan sebagai dasar pemeriksaan jawaban.
export function kamusKata(bahasa) {
  return new Set([...(DAFTAR[bahasa] || []), ...JENJANG.flatMap((j) => WORDS[j][bahasa].map(([w]) => w))]);
}

// Kamus besar (KBBI ±60 ribu kata; Inggris ±169 ribu kata dari daftar ENABLE + 10 ribu kata umum) dari game/public/kamus/*.txt,
// sudah disaring dari kata kasar. Browser memuatnya saat permainan kata dibuka; server membacanya dari disk.
const BESAR = { ID: new Set(), EN: new Set() };
const memuat = {};

export function tambahKamusBesar(bahasa, teks) {
  const set = BESAR[bahasa];
  if (!set) return;
  for (const w of String(teks).split(/\s+/)) if (/^[A-Z]{2,15}$/.test(w)) set.add(w);
}

export function muatKamusBesar(bahasa) {
  if (!BESAR[bahasa] || typeof fetch !== "function") return Promise.resolve();
  memuat[bahasa] ||= fetch(`/kamus/${bahasa.toLowerCase()}.txt`)
    .then((r) => (r.ok ? r.text() : ""))
    .then((t) => tambahKamusBesar(bahasa, t))
    .catch(() => { delete memuat[bahasa]; });   // gagal: tetap pakai kamus umum, coba lagi lain kali
  return memuat[bahasa];
}

// Pemeriksa kata sah (punya .has seperti Set): kamus umum + kamus besar.
export function pemeriksaKata(bahasa) {
  const umum = kamusKata(bahasa);
  return { has: (w) => umum.has(w) || !!BESAR[bahasa]?.has(w) };
}
